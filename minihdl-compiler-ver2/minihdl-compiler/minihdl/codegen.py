"""
codegen.py -- Phase 6: Target Code Generation.

Four back ends share one net-naming strategy, which is the only part of target
generation that is genuinely fiddly:

    net 0 / net 1        -> the literal constants
    a net bound to a port -> that port's name (and bit index, for buses)
    anything else         -> a synthetic wire  n<id>

Back ends
---------
    verilog     structural Verilog-2001, synthesisable by Vivado/Quartus/Icarus
    testbench   a self-checking Verilog testbench that sweeps all inputs
    c           a portable C evaluation function (software simulation target)
    json        the netlist as data, for external tools
"""

from __future__ import annotations
import json
from typing import Dict, List

from .ir import Netlist, ZERO, ONE, GATE_INFO

VERILOG_OP = {
    "BUF": "{a}", "NOT": "~{a}",
    "AND": "{a} & {b}", "OR": "{a} | {b}", "XOR": "{a} ^ {b}",
    "NAND": "~({a} & {b})", "NOR": "~({a} | {b})", "XNOR": "~({a} ^ {b})",
    "MUX": "{a} ? {b} : {c}",
}
C_OP = {
    "BUF": "{a}", "NOT": "(!{a})",
    "AND": "({a} & {b})", "OR": "({a} | {b})", "XOR": "({a} ^ {b})",
    "NAND": "(!({a} & {b}))", "NOR": "(!({a} | {b}))", "XNOR": "(!({a} ^ {b}))",
    "MUX": "({a} ? {b} : {c})",
}


def _port_names(nl: Netlist) -> Dict[int, str]:
    """Map nets that are directly a port bit to their HDL name.

    Inputs are registered first so that a pass-through (`out = in;`) keeps the
    input's name as the canonical reference and the output becomes an alias.
    """
    m: Dict[int, str] = {}
    for name, nets in nl.inputs:
        for i, n in enumerate(nets):
            m.setdefault(n, name if len(nets) == 1 else f"{name}[{i}]")
    for name, nets in nl.outputs:
        for i, n in enumerate(nets):
            if n in (ZERO, ONE):
                continue                       # constants keep their literal form
            m.setdefault(n, name if len(nets) == 1 else f"{name}[{i}]")
    return m


def _input_names(nl: Netlist) -> Dict[int, str]:
    m: Dict[int, str] = {}
    for name, nets in nl.inputs:
        for i, n in enumerate(nets):
            m.setdefault(n, name if len(nets) == 1 else f"{name}[{i}]")
    return m


def _decl(name: str, nets: List[int], direction: str) -> str:
    w = len(nets)
    rng = "" if w == 1 else f"[{w - 1}:0] "
    return f"{direction} {rng}{name}"


# ------------------------------------------------------------------- Verilog
def emit_verilog(nl: Netlist) -> str:
    pn = _port_names(nl)

    def ref(n: int) -> str:
        if n == ZERO:
            return "1'b0"
        if n == ONE:
            return "1'b1"
        return pn.get(n, f"n{n}")

    ports = [_decl(name, nets, "input") for name, nets in nl.inputs] + \
            [_decl(name, nets, "output") for name, nets in nl.outputs]

    L = ["// Generated by mhdlc -- the MiniHDL compiler.",
         "// Structural Verilog-2001; do not edit by hand.",
         "`default_nettype none", "",
         f"module {nl.name} ("]
    L.append("    " + ",\n    ".join(ports))
    L.append(");")

    internal = sorted({g.out for g in nl.gates} - set(pn))
    if internal:
        L.append("")
        for chunk in _chunks(internal, 8):
            L.append("    wire " + ", ".join(f"n{n}" for n in chunk) + ";")

    L.append("")
    L.append("    // ---- combinational logic " + "-" * 34)
    for g in nl.gates:
        target = pn.get(g.out, f"n{g.out}")
        args = {k: ref(v) for k, v in zip("abc", g.ins)}
        expr = VERILOG_OP[g.op].format(**args)
        note = f"   // {g.op}" + (f" @ {g.label}" if g.label else "")
        L.append(f"    assign {target} = {expr};{note}")

    L.append("")
    L.append("    // ---- output drivers " + "-" * 38)
    gate_outs = {g.out for g in nl.gates}
    for name, nets in nl.outputs:
        for i, n in enumerate(nets):
            lhs = name if len(nets) == 1 else f"{name}[{i}]"
            if n in gate_outs and pn.get(n) == lhs:
                continue                       # already driven by its own gate
            L.append(f"    assign {lhs} = {ref(n)};")
    L.append("")
    L.append("endmodule")
    L.append("`default_nettype wire")
    return "\n".join(L)


def _out_ref(nl: Netlist, net: int) -> str:
    for name, nets in nl.outputs:
        for i, n in enumerate(nets):
            if n == net:
                return name if len(nets) == 1 else f"{name}[{i}]"
    return f"n{net}"


def _chunks(seq, k):
    for i in range(0, len(seq), k):
        yield seq[i:i + k]


# ---------------------------------------------------------------- testbench
def emit_testbench(nl: Netlist, vectors) -> str:
    """Self-checking testbench with golden values from our own simulator."""
    L = ["// Auto-generated self-checking testbench for " + nl.name,
         "`timescale 1ns/1ps", "",
         "module tb_" + nl.name + ";", "    integer errors = 0;"]
    for name, nets in nl.inputs:
        w = len(nets)
        L.append(f"    reg {'' if w == 1 else f'[{w-1}:0] '}{name};")
    for name, nets in nl.outputs:
        w = len(nets)
        L.append(f"    wire {'' if w == 1 else f'[{w-1}:0] '}{name};")
    conn = ", ".join(f".{n}({n})" for n, _ in nl.inputs + nl.outputs)
    L += ["", f"    {nl.name} dut ({conn});", "", "    initial begin"]
    for assign, expect in vectors:
        for n, v in assign.items():
            L.append(f"        {n} = {len(dict(nl.inputs)[n])}'d{v};")
        L.append("        #1;")
        for n, v in expect.items():
            w = len(dict(nl.outputs)[n])
            L.append(f"        if ({n} !== {w}'d{v}) begin errors = errors + 1;"
                     f" $display(\"FAIL {n}: got %b want {w}'d{v}\", {n}); end")
    L += ["        if (errors == 0) $display(\"PASS: all vectors matched\");",
          "        else $display(\"%0d mismatches\", errors);",
          "        $finish;", "    end", "endmodule"]
    return "\n".join(L)


# ---------------------------------------------------------------------- C
def emit_c(nl: Netlist) -> str:
    pn = _input_names(nl)
    safe = nl.name

    def ref(n: int) -> str:
        if n == ZERO:
            return "0u"
        if n == ONE:
            return "1u"
        if n in pn:
            name = pn[n]
            if "[" in name:
                base, idx = name[:-1].split("[")
                return f"((in->{base} >> {idx}) & 1u)"
            return f"(in->{name} & 1u)"
        return f"n{n}"

    L = ["/* Generated by mhdlc -- software model of module " + safe + " */",
         "#include <stdint.h>", "",
         f"typedef struct {{"]
    for name, nets in nl.inputs:
        L.append(f"    uint64_t {name};   /* {len(nets)} bit(s) */")
    L.append(f"}} {safe}_in_t;", )
    L.append("")
    L.append("typedef struct {")
    for name, nets in nl.outputs:
        L.append(f"    uint64_t {name};   /* {len(nets)} bit(s) */")
    L.append(f"}} {safe}_out_t;")
    L += ["", f"void {safe}_eval(const {safe}_in_t *in, {safe}_out_t *out)", "{"]
    if nl.gates:
        for chunk in _chunks([g.out for g in nl.gates], 10):
            L.append("    unsigned " + ", ".join(f"n{n}" for n in chunk) + ";")
        L.append("")
    for g in nl.gates:
        args = {k: ref(v) for k, v in zip("abc", g.ins)}
        L.append(f"    n{g.out} = {C_OP[g.op].format(**args)};")
    L.append("")
    for name, nets in nl.outputs:
        L.append(f"    out->{name} = 0u;")
        for i, n in enumerate(nets):
            L.append(f"    out->{name} |= (uint64_t)({ref(n)}) << {i};")
    L.append("}")
    return "\n".join(L)


# -------------------------------------------------------------------- JSON
def emit_json(nl: Netlist) -> str:
    doc = {
        "module": nl.name,
        "inputs": [{"name": n, "bits": v} for n, v in nl.inputs],
        "outputs": [{"name": n, "bits": v} for n, v in nl.outputs],
        "gates": [{"op": g.op, "in": g.ins, "out": g.out, "src": g.label}
                  for g in nl.gates],
        "cells": {op: GATE_INFO[op][1] for op in sorted(GATE_INFO)},
        "stats": nl.stats(),
    }
    return json.dumps(doc, indent=2)
